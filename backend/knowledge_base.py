def normalize_topic(value: str | None) -> str:
    """Приводит тему (id или русскую подпись) к id из TOPICS."""
    if not value:
        return "other"
    v = str(value).strip()
    if v in TOPICS:
        return v
    low = v.lower()
    if low in TOPIC_ALIASES:
        return TOPIC_ALIASES[low]
    for tid, label in TOPICS.items():
        if label.lower() == low:
            return tid
    return "other"


def topic_label(topic_id: str) -> str:
    return TOPICS.get(topic_id, TOPICS["other"])


